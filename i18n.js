let LANG = (function(){
  try { return localStorage.getItem('qandil.lang') || 'ar'; } catch(e){ return 'ar'; }
})();

function t(key){
  const d = I18N[LANG] || I18N.ar;
  return d[key] !== undefined ? d[key] : (I18N.ar[key] || key);
}

function applyI18n(){
  document.documentElement.lang = LANG;
  document.documentElement.dir = (LANG === 'ar') ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    const k = el.getAttribute('data-i18n');
    const v = t(k);
    if (v) el.textContent = v;
  });
  if (window.onLangApplied) window.onLangApplied();
}

function setLang(l){
  LANG = l;
  try { localStorage.setItem('qandil.lang', l); } catch(e){}
  applyI18n();
}